function result=bold_unwarp_run(spec,cfg)
%BOLD_UNWARP_RUN 用 TOPUP Hz 场配准 SBRef 后校正原始 4D BOLD。
% 实现 HCP 的关键步骤：SE 场模拟 BOLD 畸变 → 刚体配准至 SBRef →
% 在 SBRef 空间重建 BOLD 专用场/变形 → 单次畸变重采样。原始输入只读。
plan=psy.bold_unwarp_validate(spec,cfg);
if ~isscalar(cfg.jacobianModulation)||~islogical(cfg.jacobianModulation)
    error('psy:BoldUnwarpConfig','jacobianModulation 必须是逻辑标量');
end
if ~isnumeric(cfg.registrationSearchDegrees)||~isscalar(cfg.registrationSearchDegrees)|| ...
        ~isfinite(cfg.registrationSearchDegrees)||cfg.registrationSearchDegrees<0||cfg.registrationSearchDegrees>90
    error('psy:BoldUnwarpConfig','registrationSearchDegrees 必须是 0~90 度');
end
run=struct('subject',spec.subject,'session',spec.session,'name',spec.run);
out=psy.run_output_dir(cfg.outputRoot,run);
if isfolder(out), error('psy:BoldUnwarpExisting','已有输出目录，拒绝覆盖: %s',out); end
mkdir(out);
save(fullfile(out,'plan.mat'),'spec','cfg','plan');
f=@(name)fullfile(out,name);
w=@(name)quote(wslpath(f(name)));
q= @quote;
se=quote(wslpath(plan.seMagnitude)); field=quote(wslpath(plan.fieldHz));
sbref=quote(wslpath(spec.sbref)); bold=quote(wslpath(spec.bold));
dwell=sprintf('%.12f',plan.effectiveEchoSpacingSeconds);
axis='xyz'; direction=axis(plan.phaseAxis);
if plan.phaseVector(plan.phaseAxis)<0, direction=[direction '-']; end
search=sprintf('%.1f',cfg.registrationSearchDegrees);
% TOPUP --fout 单位 Hz；fugue --loadfmap 需要 rad/s。
lines={'#!/usr/bin/env bash','set -euo pipefail', ...
    ['exec > ' w('fsl.log') ' 2>&1'], ...
    ['export FSLDIR=' q(cfg.fslRoot)],'export FSLOUTPUTTYPE=NIFTI_GZ', ...
    ['export PATH=' q([cfg.fslRoot '/bin']) ':"$PATH"'], ...
    ['cd ' q(wslpath(out))], ...
    ['"$FSLDIR/bin/fslmaths" ' field ' -mul 6.283185307179586 ' w('field_rad') ' -odt float'], ...
    ['"$FSLDIR/bin/fugue" --loadfmap=' w('field_rad') ' --dwell=' dwell ' --saveshift=' w('se_shift')], ...
    ['"$FSLDIR/bin/convertwarp" --relout --rel --ref=' se ' --shiftmap=' w('se_shift') ...
        ' --shiftdir=' direction ' --out=' w('se_bold_warp')], ...
    ['"$FSLDIR/bin/applywarp" --rel --interp=spline -i ' se ' -r ' se ...
        ' -w ' w('se_bold_warp') ' -o ' w('se_simulated_bold')], ...
    ['"$FSLDIR/bin/flirt" -interp spline -dof 6 -cost corratio -in ' w('se_simulated_bold') ...
        ' -ref ' sbref ' -omat ' w('se_to_sbref.mat') ' -out ' w('se_registered') ...
        ' -searchrx -' search ' ' search ' -searchry -' search ' ' search ...
        ' -searchrz -' search ' ' search], ...
    ['"$FSLDIR/bin/flirt" -in ' w('field_rad') ' -ref ' sbref ...
        ' -applyxfm -init ' w('se_to_sbref.mat') ' -interp trilinear -out ' w('field_sbref_rad')], ...
    ['"$FSLDIR/bin/fugue" --loadfmap=' w('field_sbref_rad') ' --dwell=' dwell ...
        ' --saveshift=' w('sbref_shift')], ...
    ['"$FSLDIR/bin/convertwarp" --relout --rel --ref=' sbref ' --shiftmap=' w('sbref_shift') ...
        ' --shiftdir=' direction ' --out=' w('bold_warp')], ...
    ['"$FSLDIR/bin/applywarp" --rel --interp=spline -i ' sbref ' -r ' sbref ...
        ' -w ' w('bold_warp') ' --datatype=float -o ' w('sbref_unwarped')], ...
    ['"$FSLDIR/bin/applywarp" --rel --interp=spline -i ' bold ' -r ' sbref ...
        ' -w ' w('bold_warp') ' --datatype=float -o ' w('bold_unwarped') ]};
if cfg.jacobianModulation
    lines=[lines,{ ...
        ['"$FSLDIR/bin/convertwarp" --rel -w ' w('bold_warp') ' -r ' sbref ...
            ' --jacobian=' w('jacobian_8') ' -o ' w('warp_tmp')], ...
        ['"$FSLDIR/bin/fslmaths" ' w('jacobian_8') ' -Tmean ' w('jacobian_raw')], ...
        ['"$FSLDIR/bin/fslmaths" ' w('jacobian_raw') ' -thr 0 ' w('jacobian')], ...
        ['"$FSLDIR/bin/fslmaths" ' w('sbref_unwarped') ' -mul ' w('jacobian') ' ' w('sbref_unwarped_jac')], ...
        ['"$FSLDIR/bin/fslmaths" ' w('bold_unwarped') ' -mul ' w('jacobian') ' ' w('bold_unwarped_jac')]}];
end
script=f('run_bold_unwarp.sh'); fid=fopen(script,'w');
if fid<0, error('psy:BoldUnwarpWrite','无法写脚本'); end
fprintf(fid,'%s\n',lines{:}); fclose(fid);
result=struct('status','planned_not_executed','outputDir',out,'plan',plan,'script',script);
if ~cfg.execute, return; end
cmd=['wsl -d ' cfg.wslDistro ' -- /bin/bash "' wslpath(script) '"'];
[code,~]=system(cmd);result.exitCode=code;
if code~=0
    save(f('FAILED.mat'),'result');
    error('psy:BoldUnwarpFailed','FSL 退出码 %d；查看 %s',code,f('fsl.log'));
end
verified=psy.bold_unwarp_finalize(spec,cfg,plan,out);
result.status=verified.status;result.qc=verified.qc;
end
function p=wslpath(w)
w=char(string(w));
if numel(w)<3||~isletter(w(1))||w(2)~=':'||~ismember(w(3),['\' '/'])
    error('psy:BoldUnwarpPath','仅支持 WSL 自动挂载的盘符绝对路径: %s',w);
end
p=['/mnt/' lower(w(1)) strrep(w(3:end),'\','/')];
end
function s=quote(value)
s=['''' strrep(char(value),'''','''"''"''') ''''];
end
